import { createHmac } from "node:crypto";
import {
  identityServiceById,
  maskIdentifier,
  type IdentityResultDTO,
  type IdentityServiceId,
} from "@paylane/shared";
import { env, identityVendorConfigured } from "../../config/env";
import { buildPdfDocument } from "../../lib/pdf";

export type IdentityAdapterMode = "HTTP" | "SANDBOX";

export interface IdentityVendorInput {
  service: IdentityServiceId;
  reference: string;
  fields: Record<string, string>;
}

export type IdentityVendorOutcome =
  | { status: "SUCCESS"; providerRef: string; result: IdentityResultDTO }
  | { status: "FAILED"; reason: string; retryable: boolean; providerRef?: string };

export interface IdentityAdapter {
  readonly mode: IdentityAdapterMode;
  readonly name: string;
  verify(input: IdentityVendorInput): Promise<IdentityVendorOutcome>;
}

/* ── Sandbox ─────────────────────────────────────────────────────────────── */

const FIRST_NAMES = ["Adaeze", "Chinedu", "Tunde", "Ngozi", "Ibrahim", "Funke", "Emeka", "Aisha"];
const MIDDLE_NAMES = ["Chinwe", "Oluwaseun", "Amina", "Kelechi", "Ifeoma", "Musa", "Tolulope"];
const LAST_NAMES = ["Okonkwo", "Balogun", "Bakare", "Eze", "Musa", "Adeyemi", "Nwosu", "Ibrahim"];
const STATES = ["Lagos", "Anambra", "Oyo", "Kano", "Rivers", "Enugu", "Kaduna", "Delta"];
const BANKS = ["Access Bank", "First Bank of Nigeria", "GTBank", "UBA", "Zenith Bank", "Kuda MFB"];

function stableIndex(seed: number, length: number): number {
  return Math.abs(seed) % length;
}

function dobFrom(seed: number): string {
  const year = 1975 + (seed % 25);
  const month = 1 + (seed % 12);
  const day = 1 + (seed % 27);
  return `${String(year).padStart(4, "0")}-${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")}`;
}

function mockIdentity(input: IdentityVendorInput): IdentityResultDTO {
  const service = identityServiceById(input.service);
  const joined = Object.values(input.fields).join("");
  const digits = joined.replace(/\D/g, "");
  let seed = 0;
  for (const character of joined) seed = (seed + character.charCodeAt(0)) % 100_000;

  const providedFirst = input.fields.firstName?.trim();
  const providedLast = input.fields.lastName?.trim();
  const firstName = providedFirst || FIRST_NAMES[stableIndex(seed, FIRST_NAMES.length)];
  const middleName = MIDDLE_NAMES[stableIndex(seed + 3, MIDDLE_NAMES.length)];
  const lastName = providedLast || LAST_NAMES[stableIndex(seed + 7, LAST_NAMES.length)];
  const fullName = `${firstName} ${middleName} ${lastName}`.toUpperCase();
  const dateOfBirth = input.fields.dateOfBirth || dobFrom(seed);
  const gender = seed % 2 === 0 ? "Female" : "Male";
  const state = input.fields.state || STATES[stableIndex(seed + 5, STATES.length)] || "Lagos";
  const nin = input.fields.nin || input.fields.guardianNin || digits.slice(0, 11).padStart(11, "0");
  const bvn = input.fields.bvn || digits.slice(-11).padStart(11, "0");
  const phone = input.fields.phone || input.fields.newPhone || "08030000000";

  const base: IdentityResultDTO = {
    kind: service?.resultKind ?? "ACKNOWLEDGEMENT",
    fields: [],
    document: null,
    note: "Sandbox result. No live NIMC or NIBSS record was queried.",
  };

  if (input.service === "BVN_VERIFICATION") {
    return {
      ...base,
      kind: "IDENTITY",
      fields: [
        { label: "Account name", value: fullName },
        { label: "Date of birth", value: dateOfBirth },
        { label: "BVN", value: maskIdentifier(bvn) },
        { label: "Bank on record", value: BANKS[stableIndex(seed + 2, BANKS.length)] ?? "Access Bank" },
        { label: "Phone on record", value: maskIdentifier(phone) },
        { label: "Watchlist", value: "No adverse match" },
      ],
    };
  }

  if (input.service === "NIN_VERIFICATION") {
    return {
      ...base,
      kind: "IDENTITY",
      fields: [
        { label: "Full name", value: fullName },
        { label: "Date of birth", value: dateOfBirth },
        { label: "Gender", value: gender },
        { label: "NIN", value: maskIdentifier(nin) },
        { label: "State of origin", value: state },
        { label: "Record status", value: "Verified" },
      ],
    };
  }

  if (input.service === "NIN_SLIP") {
    const contentBase64 = buildPdfDocument({
      title: "NATIONAL IDENTIFICATION NUMBER SLIP",
      subtitle: "Federal Republic of Nigeria · National Identity Management Commission",
      lines: [
        { label: "Full name", value: fullName },
        { label: "Date of birth", value: dateOfBirth },
        { label: "Gender", value: gender },
        { label: "NIN", value: nin },
        { label: "State of origin", value: state },
        { label: "Issued", value: new Date().toISOString().slice(0, 10) },
        { label: "Reference", value: input.reference },
      ],
      footer:
        "Sandbox document generated by Paylane for testing. It is not a government-issued NIN slip and must not be presented as one.",
    });
    return {
      ...base,
      kind: "DOCUMENT",
      fields: [
        { label: "Full name", value: fullName },
        { label: "NIN", value: maskIdentifier(nin) },
        { label: "Record status", value: "Verified" },
      ],
      document: {
        fileName: `NIN-slip-${input.reference}.pdf`,
        mimeType: "application/pdf",
        contentBase64,
      },
    };
  }

  if (input.service === "NIN_PERSONALIZATION") {
    return {
      ...base,
      fields: [
        { label: "Full name", value: fullName },
        { label: "NIN", value: maskIdentifier(nin) },
        { label: "Card type", value: "Personalised national e-ID card" },
        { label: "Collection centre", value: `NIMC centre, ${state} state` },
        { label: "Expected ready", value: "3 to 5 working days" },
        { label: "Request reference", value: input.reference },
      ],
    };
  }

  if (input.service === "IPE_CLEARANCE") {
    return {
      ...base,
      fields: [
        { label: "Full name", value: fullName },
        { label: "NIN", value: maskIdentifier(nin) },
        { label: "Clearance status", value: "Queued for IPE review" },
        { label: "Desk", value: "Identity records unit" },
        { label: "Request reference", value: input.reference },
      ],
    };
  }

  const subject = input.fields.firstName
    ? `${input.fields.firstName} ${input.fields.lastName ?? ""}`.trim()
    : maskIdentifier(nin);

  return {
    ...base,
    kind: "ACKNOWLEDGEMENT",
    fields: [
      { label: "Service", value: service?.name ?? input.service },
      { label: "Subject", value: subject },
      { label: "Status", value: "Accepted for processing" },
      { label: "Request reference", value: input.reference },
      { label: "Submitted", value: new Date().toISOString().slice(0, 16).replace("T", " ") },
      { label: "Expected completion", value: service?.turnaroundLabel ?? "1 to 3 working days" },
      {
        label: "Next step",
        value:
          input.service.includes("ENROLMENT")
            ? "The applicant will be contacted with an appointment centre and time."
            : "Support will contact you if any supporting document is required.",
      },
    ],
  };
}

class SandboxIdentityAdapter implements IdentityAdapter {
  readonly mode = "SANDBOX" as const;
  readonly name = "Paylane sandbox";

  async verify(input: IdentityVendorInput): Promise<IdentityVendorOutcome> {
    const primary = input.fields.nin ?? input.fields.bvn ?? input.fields.guardianNin ?? "";
    await new Promise((resolve) => setTimeout(resolve, 350));

    if (primary.startsWith("999")) {
      return {
        status: "FAILED",
        reason: "The identity provider did not respond in time. Try again shortly.",
        retryable: true,
      };
    }
    if (primary.endsWith("0000")) {
      return {
        status: "FAILED",
        reason: "No record was found for that identifier. Check the number and try again.",
        retryable: false,
      };
    }

    return {
      status: "SUCCESS",
      providerRef: `MCK-${input.reference.slice(-8).toUpperCase()}`,
      result: mockIdentity(input),
    };
  }
}

/* ── HTTP vendor ─────────────────────────────────────────────────────────── */

interface HttpVendorBody {
  status?: string | boolean;
  success?: boolean;
  code?: string | number;
  message?: string;
  reference?: string;
  data?: Record<string, unknown>;
}

function readString(source: Record<string, unknown>, ...keys: string[]): string | null {
  for (const key of keys) {
    const value = source[key];
    if (typeof value === "string" && value.trim()) return value.trim();
    if (typeof value === "number") return String(value);
  }
  return null;
}

function httpResult(
  service: IdentityServiceId,
  body: HttpVendorBody,
  reference: string,
): IdentityVendorOutcome {
  const data = body.data ?? {};
  const status = typeof body.status === "string" ? body.status.toLowerCase() : "";
  const success =
    body.success === true ||
    body.code === "00" ||
    body.code === 200 ||
    ["success", "successful", "completed", "verified"].includes(status);

  if (!success) {
    return {
      status: "FAILED",
      reason:
        body.message ??
        readString(data, "message", "reason") ??
        "The identity provider could not complete this request.",
      retryable: body.code === 429 || (typeof body.code === "number" && body.code >= 500),
      providerRef: readString(data, "reference", "providerRef") ?? undefined,
    };
  }

  const first = readString(data, "firstName");
  const last = readString(data, "lastName");
  const combined = `${first ?? ""} ${last ?? ""}`.trim();
  const fullName = readString(data, "fullName", "name", "accountName") ?? (combined || null);
  const dob = readString(data, "dateOfBirth", "dob", "birthDate");
  const gender = readString(data, "gender");
  const state = readString(data, "state", "stateOfOrigin");
  const phone = readString(data, "phone", "phoneNumber");
  const address = readString(data, "address", "residentialAddress");
  const nin = readString(data, "nin");
  const bvn = readString(data, "bvn");

  const fields: IdentityResultDTO["fields"] = [];
  const push = (label: string, value: string | null) => {
    if (value) fields.push({ label, value });
  };
  push("Full name", fullName);
  push("Date of birth", dob);
  push("Gender", gender);
  push("NIN", nin ? maskIdentifier(nin) : null);
  push("BVN", bvn ? maskIdentifier(bvn) : null);
  push("Phone", phone ? maskIdentifier(phone) : null);
  push("Address", address);
  push("State", state);
  push("Request reference", readString(data, "requestReference", "ticketNumber") ?? reference);
  push("Status", readString(data, "statusText", "recordStatus"));

  const serviceDef = identityServiceById(service);
  const documentBase64 = readString(data, "documentBase64", "pdfBase64", "document");
  const fileName = readString(data, "documentName", "fileName") ?? `${service}-${reference}.pdf`;
  const mimeType = readString(data, "documentMimeType", "mimeType") ?? "application/pdf";

  return {
    status: "SUCCESS",
    providerRef: readString(data, "providerRef", "reference", "id") ?? reference,
    result: {
      kind: serviceDef?.resultKind ?? "ACKNOWLEDGEMENT",
      fields,
      document: documentBase64
        ? { fileName, mimeType, contentBase64: documentBase64 }
        : null,
      note: readString(data, "note") ?? null,
    },
  };
}

class HttpIdentityAdapter implements IdentityAdapter {
  readonly mode = "HTTP" as const;
  readonly name = "Configured identity vendor";

  async verify(input: IdentityVendorInput): Promise<IdentityVendorOutcome> {
    const baseUrl = env.identity.baseUrl;
    const apiKey = env.identity.apiKey;
    if (!baseUrl || !apiKey) {
      return {
        status: "FAILED",
        reason: "The identity provider is not configured.",
        retryable: true,
      };
    }

    const payload = JSON.stringify({
      service: input.service,
      reference: input.reference,
      ...input.fields,
    });
    const signature = createHmac("sha256", env.identity.apiSecret ?? apiKey)
      .update(payload)
      .digest("hex");

    try {
      const response = await fetch(`${baseUrl.replace(/\/$/, "")}${env.identity.verifyPath}`, {
        method: "POST",
        headers: {
          "content-type": "application/json",
          accept: "application/json",
          authorization: `Bearer ${apiKey}`,
          "x-paylane-signature": signature,
          "idempotency-key": input.reference,
        },
        body: payload,
        signal: AbortSignal.timeout(env.identity.timeoutMs),
      });

      const text = await response.text();
      let body: HttpVendorBody = {};
      try {
        body = text ? (JSON.parse(text) as HttpVendorBody) : {};
      } catch {
        return {
          status: "FAILED",
          reason: "The identity provider returned a response we could not read.",
          retryable: response.status >= 500,
        };
      }

      if (!response.ok && !body.code && body.success === undefined) {
        return {
          status: "FAILED",
          reason: body.message ?? `The identity provider returned HTTP ${response.status}.`,
          retryable: response.status === 429 || response.status >= 500,
        };
      }

      return httpResult(input.service, body, input.reference);
    } catch (error) {
      const timedOut = error instanceof Error && error.name === "TimeoutError";
      return {
        status: "FAILED",
        reason: timedOut
          ? "The identity provider did not respond in time."
          : "The identity provider could not be reached.",
        retryable: true,
      };
    }
  }
}

/* ── Registry ────────────────────────────────────────────────────────────── */

const sandbox = new SandboxIdentityAdapter();
const http = new HttpIdentityAdapter();

export function identityAdapterMode(): IdentityAdapterMode {
  if (env.identity.mode === "MOCK") return "SANDBOX";
  if (env.identity.mode === "HTTP") return "HTTP";
  return identityVendorConfigured ? "HTTP" : "SANDBOX";
}

export function identityAdapter(): IdentityAdapter {
  return identityAdapterMode() === "HTTP" ? http : sandbox;
}

/** Throws before money moves if the operator asked for live mode without keys. */
export function assertIdentityProviderReady(): void {
  if (env.identity.mode === "HTTP" && !identityVendorConfigured) {
    throw new Error(
      "Identity vendor is set to HTTP but IDENTITY_VENDOR_BASE_URL or IDENTITY_VENDOR_API_KEY is blank.",
    );
  }
}
